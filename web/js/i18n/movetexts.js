/** Patch the move catalog in place with the texts of `lang`. */
export function applyMoveTexts(lang) {
  const pack = MOVE_TEXTS[lang] ?? MOVE_TEXTS.zh;
  curLang = MOVE_TEXTS[lang] ? lang : "zh";
  const fit = FIT_NAMES[curLang] ?? FIT_NAMES.zh;
  for (const [id, m] of Object.entries(MOVES)) {
    if (fit[id]) m.name = fit[id];
  }
  for (const [id, m] of Object.entries(DANCE_MOVES)) {
    const o = pack.dm[id];
    if (!o) continue;
    m.name = o[0];
    m.tip = o[1];
    if (o[2]) m.steps = o[2];
  }
  for (const [id, ui] of Object.entries(MOVE_UI)) {
    const dm = pack.dm[id];
    ui.tip = pack.ui[id] ?? dm?.[1] ?? ui.tip;
  }
  // DANCE_NAMES feeds charts / HUD; keep it in sync with the patched names
  for (const [id, n] of Object.entries(DANCE_NAMES)) {
    if (DANCE_MOVES[id]) n.name = DANCE_MOVES[id].name;
  }
}
